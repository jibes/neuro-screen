import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import adapter from '@sveltejs/adapter-static';

/**
 * Base path from VITE_BASE (portfolio standard), e.g. "/neuro-screen/" on GitHub Pages.
 * SvelteKit needs it absolute without a trailing slash; "./" or unset means the root.
 */
const rawBase = process.env.VITE_BASE ?? '';
const base = rawBase === './' ? '' : rawBase.replace(/\/$/, '');

/**
 * Android build (NATIVE=1, see `build:native`): Capacitor serves index.html for every route, so the
 * app ships as a pure SPA shell. No CSP there: the Capacitor bridge is injected as inline script.
 */
const native = process.env.NATIVE === '1';

/** CSP hash of the pre-paint theme script in app.html (SvelteKit hashes only its own scripts) */
const themeScript = readFileSync('src/app.html', 'utf8').match(/<script>([\s\S]*?)<\/script>/)?.[1];
if (!themeScript) throw new Error('Theme script not found in src/app.html');
const themeHash = `sha256-${createHash('sha256').update(themeScript).digest('base64')}`;

/** @type {import('@sveltejs/kit').Config} */
const config = {
  kit: {
    adapter: adapter({
      // GitHub Pages serves 404.html for unknown paths, so dynamic routes
      // (e.g. /ergebnisse/[testId]) fall back to the client-side app
      fallback: native ? 'index.html' : '404.html',
    }),
    prerender: native ? { entries: [], handleUnseenRoutes: 'ignore' } : undefined,
    paths: { base },
    // The service worker is generated by @vite-pwa/sveltekit (Workbox)
    serviceWorker: { register: false },
    // Emitted as <meta http-equiv> in the static pages; no network access beyond the own origin
    csp: native
      ? undefined
      : {
          mode: 'hash',
          directives: {
            'default-src': ['self'],
            'script-src': ['self', themeHash],
            // Svelte transitions and style attributes need inline styles
            'style-src': ['self', 'unsafe-inline'],
            'img-src': ['self', 'data:', 'blob:'],
            'connect-src': ['self'],
            'worker-src': ['self'],
            'manifest-src': ['self'],
            'object-src': ['none'],
            'base-uri': ['self'],
            'form-action': ['self'],
          },
        },
  },
};

export default config;
